  assert m.body_jntnum[b]==1
  j=m.body_jntadr[b];assert m.jnt_type[j]==mujoco.mjtJoint.mjJNT_HINGE
  np.testing.assert_allclose(m.jnt_axis[j],[0,0,1]);row=int(m.jnt_qposadr[j]-7);jpos=m.jnt_pos[j]
