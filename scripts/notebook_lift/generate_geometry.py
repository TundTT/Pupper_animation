s+=''' static V3 add(V3 a,const V3& b){for(int i=0;i<3;++i)a[i]+=b[i];return a;}
 static V3 mv(const M3& a,const V3& v){V3 o{};for(int i=0;i<3;++i)for(int j=0;j<3;++j)o[i]+=a[3*i+j]*v[j];return o;}
 static M3 mul(const M3& a,const M3& b){M3 o{};for(int i=0;i<3;++i)for(int j=0;j<3;++j)for(int k=0;k<3;++k)o[3*i+j]+=a[3*i+k]*b[3*k+j];return o;}
 static std::array<double,4> bottoms(const std::array<double,12>& q,const V3& gravity){
  std::array<V3,bodies.size()> p{};std::array<M3,bodies.size()> R{};
  R[0]=R[1]=M3{1,0,0,0,1,0,0,0,1};
  for(unsigned b=2;b<bodies.size();++b){auto t=bodies[b];M3 local=t.rotation;V3 position=t.pos;
   if(t.joint>=0){double co=std::cos(q[t.joint]),si=std::sin(q[t.joint]);M3 spin{co,-si,0,si,co,0,0,0,1};auto offset=mv(spin,t.pivot);for(int i=0;i<3;++i)offset[i]=t.pivot[i]-offset[i];position=add(position,mv(local,offset));local=mul(local,spin);}
   p[b]=add(p[t.parent],mv(R[t.parent],position));R[b]=mul(R[t.parent],local);
  }
  std::array<double,4> out{};
  for(int k=0;k<4;++k){int b=wheel_body[k];auto center=add(p[b],mv(R[b],wheel_pos[k]));auto orient=mul(R[b],wheel_rotation[k]);double z=0,az=0;for(int i=0;i<3;++i){z-=center[i]*gravity[i];az-=orient[3*i+2]*gravity[i];}out[k]=z-.048*std::sqrt(std::max(0.,1-az*az))-.01675*std::abs(az);}
  return out;
 }
};
}
'''
a.out.write_text(s)
